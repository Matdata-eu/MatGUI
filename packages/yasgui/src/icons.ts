export type IconName = keyof typeof paths;

export function icon(name: IconName, size = 18, strokeWidth = 1.75): string {
  return `<svg class="yasgui-icon" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths[name]}</svg>`;
}

/**
 * Button with a Lucide icon and an optional visible text label.
 */
export function iconButton(
  name: IconName,
  label: string,
  options: { className?: string; showLabel?: boolean; title?: string; size?: number } = {},
): HTMLButtonElement {
  const button = document.createElement("button");
  button.type = "button";
  if (options.className) button.className = options.className;
  button.setAttribute("aria-label", label);
  button.title = options.title || label;
  button.innerHTML = icon(name, options.size) + (options.showLabel ? `<span class="yasgui-btnLabel"></span>` : "");
  if (options.showLabel) (button.querySelector(".yasgui-btnLabel") as HTMLElement).textContent = label;
  return button;
}

/** Shortcut label for the run key binding, e.g. "Ctrl ↵" or "⌘ ↵" */
export function runShortcutLabel(): string {
  const isMac = typeof navigator !== "undefined" && /Mac|iPhone|iPad/.test(navigator.platform || navigator.userAgent);
  return isMac ? "⌘ ↵" : "Ctrl ↵";
}
